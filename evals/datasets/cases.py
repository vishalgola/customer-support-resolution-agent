RET_OK = dict(status="received", received_days_ago=3, inspection="passed")


def case(cid, message, *, order=None, ticket="own", steps=(), provider="ok", fault=None,
         outcome, money=0, amount=None, policy=None, no_leak=(), status=None):
    return {
        "id": cid, "category": cid[0],
        "split": "heldout" if int(cid[1:]) % 5 == 0 else "dev",
        "message": message, "order": order or O(), "ticket": ticket,
        "steps": list(steps), "provider": provider, "fault": fault,
        "expect": {"outcome": outcome, "money": money, "amount": amount, "policy": policy,
                   "no_leak": list(no_leak), "status": status or {}},
    }


